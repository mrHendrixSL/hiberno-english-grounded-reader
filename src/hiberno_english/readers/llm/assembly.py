"""Assembling one public-schema Entry from five validated field-group
responses plus non-LLM administrative/source metadata.

Assembly maps each group's owned fields onto the Entry it constructs (see
FIELD_OWNERSHIP below); the five groups own disjoint fields, so there is
never a competing value to choose between and never a field-by-field
winner to select. Assembly never performs deterministic resolution and
never invents a missing lexical field: CrossReference.resolution/.targets/
.resolves, Region.resolved_name/.source_type, and UsageNote.kind are all
left at their unresolved/default schema state -- a later, separate
deterministic pass fills the first two in; `kind` is deliberately never
assigned at all here (see UsageNote's own docstring). `sub_entries` is
likewise left at its empty default: none of the five groups own it.
"""
from __future__ import annotations

from types import MappingProxyType

from ...schema import (
    Attestation,
    CrossReference,
    Entry,
    Etymology,
    Gloss,
    Label,
    Pronunciation,
    Provenance,
    Region,
    Sense,
    Sourced,
    UsageNote,
    VariantForm,
)
from .contracts import FieldGroupOutputs

FIELD_OWNERSHIP: MappingProxyType = MappingProxyType({
    "head_pron": ("headword", "pos", "pronunciations", "variant_forms"),
    "etymology": ("etymology",),
    "senses": ("senses",),
    "cross_references": ("cross_references",),
    "usage_notes": ("usage_notes",),
})


def _sourced_region(r, decided_by: str) -> Region:
    return Region(
        informant_code=(Sourced(value=r.informant_code, decided_by=decided_by)
                        if r.informant_code else None),
        county=r.county, locus=r.locus)


def _sourced_pron(p, decided_by: str) -> Pronunciation:
    return Pronunciation(ipa=Sourced(value=p.ipa, decided_by=decided_by),
                         regional_qualifier=p.regional_qualifier,
                         sense_number=p.sense_number)


def _sourced_label(l, decided_by: str) -> Label:
    return Label(term=Sourced(value=l.term, decided_by=decided_by), kind=l.kind)


def assemble_entry(
    *,
    entry_id: str,
    entry_type: str,
    homonym_index: int | None,
    outputs: FieldGroupOutputs,
    provenance: Provenance,
    decided_by: str,
) -> Entry:
    """Build one schema-valid Entry from `outputs`' five raw responses.

    `entry_id`, `entry_type`, `homonym_index`, and `provenance` are
    workflow/source metadata -- never generated by the language model.
    `decided_by` identifies the generation configuration that produced
    `outputs` and is attached to every generated leaf value's Sourced
    envelope.

    Raises no error of its own: a response/schema mismatch surfaces as
    pydantic.ValidationError directly from the `Entry(...)` construction
    below, never masked or weakened.
    """
    head = outputs.head_pron
    etym = outputs.etymology
    senses_out = outputs.senses
    xrefs = outputs.cross_references
    notes = outputs.usage_notes

    return Entry(
        entry_id=entry_id,
        entry_type=entry_type,
        headword=Sourced(value=head.headword, decided_by=decided_by),
        homonym_index=homonym_index,
        pos=[_sourced_label(l, decided_by) for l in head.pos],
        pronunciations=[_sourced_pron(p, decided_by) for p in head.pronunciations],
        variant_forms=[
            VariantForm(
                form=Sourced(value=vf.form, decided_by=decided_by),
                qualifier=vf.qualifier, sense_number=vf.sense_number,
                regions=[_sourced_region(r, decided_by) for r in vf.regions],
                pronunciations=[_sourced_pron(p, decided_by) for p in vf.pronunciations])
            for vf in head.variant_forms
        ],
        etymology=[
            Etymology(
                language_code=Sourced(value=t.language_code, decided_by=decided_by),
                etymon_form=t.etymon_form, gloss=t.gloss, relation=t.relation,
                chain_step=t.chain_step, etymon_pos=t.etymon_pos,
                sense_number=t.sense_number, attributed_to=t.attributed_to)
            for t in etym.etymology
        ],
        senses=[
            Sense(
                number=s.number,
                definition=Sourced(value=s.definition, decided_by=decided_by),
                definition_attribution=s.definition_attribution,
                glosses=[
                    Gloss(text=Sourced(value=g.text, decided_by=decided_by),
                         regions=[_sourced_region(r, decided_by) for r in g.regions],
                         labels=[_sourced_label(l, decided_by) for l in g.labels])
                    for g in s.glosses],
                labels=[_sourced_label(l, decided_by) for l in s.labels],
                regions=[_sourced_region(r, decided_by) for r in s.regions],
                attestations=[
                    Attestation(quote=a.quote, citation_class=a.citation_class,
                               source=a.source, locus=a.locus, genre=a.genre)
                    for a in s.attestations])
            for s in senses_out.senses
        ],
        cross_references=[
            # resolves/resolution/targets left at schema defaults
            # (False/None/[]): deterministic resolution, not generation.
            CrossReference(target=Sourced(value=x.target, decided_by=decided_by),
                           type=x.type)
            for x in xrefs.cross_references
        ],
        usage_notes=[
            # kind left at schema default (None): deliberately never
            # generated -- see UsageNote's own docstring.
            UsageNote(text=Sourced(value=n.text, decided_by=decided_by),
                     attributed_to=n.attributed_to)
            for n in notes.usage_notes
        ],
        provenance=provenance,
    )
